#!/usr/bin/env python3
"""Compose startup instructions in the selected project, without replacing native ones."""

import os
import subprocess
import tempfile
from pathlib import Path

MARKER = "<!-- Generated by codex-jail from CLAUDE.md + CLAUDE.local.md; do not edit. -->"
ENV_MARKER = "<!-- Generated by codex-jail: container environment; do not edit. -->"
SEAT_MARKER = "<!-- composed at container start by tools/jail-entrypoint.sh from agents/jail-seat-card.md — edit THAT file, not this one -->"


def atomic_write(target, content):
    fd, temp = tempfile.mkstemp(prefix=".codex-context-", dir=target.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(content)
        os.replace(temp, target)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def bootstrap(project, codex_home, seat=False):
    """Global container facts plus the current seat card, before CLI startup."""
    global_card = codex_home / "AGENTS.md"
    if not global_card.is_symlink() and (not global_card.exists() or global_card.read_text().startswith(ENV_MARKER)):
        atomic_write(
            global_card,
            ENV_MARKER
            + f"""

# Codex jail environment

- Running as node in a Debian Docker jail with passwordless sudo.
- The host launcher bypasses Codex approvals and sandboxing; Docker is the boundary.
- Initial working directory: `{project}`. Mounted workspace files are host files.
- Codex auth, config, and sessions persist under `{codex_home}`.
- Upload inbox: `{os.environ.get("UPLOAD_DIR", str(project / "uploads"))}`.
- Project tools come from Devbox and the shared `/nix` store; use the project's devbox.json.
- Git and service access depend on provisioned credentials. Verify availability;
  do not assume a credential or service is present merely because a card mentions it.
- Homelab skills, when mounted, are linked at `/home/node/.agents/skills`.
- Source instructions may mention Claude-specific commands or hooks; those require
  a Codex equivalent and are not automatically implemented by reading this card.
""",
        )
        if os.environ.get("STACK_NAME"):
            # The rendered prefix contains presence/scope only, never token values.
            # Omit the Claude-specific shared tail; the runtime facts above replace it.
            stack_card = Path("/workspace/CLAUDE.local.md").read_text().split("\n---\n", 1)[0]
            atomic_write(global_card, global_card.read_text() + "\n" + stack_card + "\n")
    else:
        print("codex-context: preserving user global AGENTS.md; environment card not generated")
    if seat:
        source = project / "agents/jail-seat-card.md"
        target = project / "CLAUDE.local.md"
        if not source.is_file():
            raise RuntimeError("homelab seat card source missing; refusing stale startup context")
        if target.is_symlink() or (target.exists() and not target.read_text().startswith(SEAT_MARKER)):
            raise RuntimeError("CLAUDE.local.md is not the generated seat card; leaving it untouched")
        atomic_write(target, SEAT_MARKER + "\n" + source.read_text())
    compose(project)


def compose(project):
    target = project / "AGENTS.md"

    def git(*args):
        return subprocess.run(["git", "-C", str(project), *args], capture_output=True, text=True, check=True).stdout.strip()

    # A native or tracked AGENTS.md belongs to its author, even with our marker.
    if target.is_symlink() or (target.exists() and not target.read_text().startswith(MARKER)):
        print("codex-context: using native AGENTS.md; Claude files not merged")
        return
    if not any((project / name).exists() for name in ("CLAUDE.md", "CLAUDE.local.md", "AGENTS.md")):
        return
    try:
        tracked = git("ls-files", "--", "AGENTS.md")
    except subprocess.CalledProcessError:
        raise RuntimeError("Startup context requires a Git repository") from None
    if tracked:
        print("codex-context: using tracked AGENTS.md; Claude files not merged")
        return
    if (project / "AGENTS.override.md").exists():
        print("codex-context: AGENTS.override.md takes precedence over the generated merge")
    sources = [project / name for name in ("CLAUDE.md", "CLAUDE.local.md")]
    parts = [MARKER]
    for source in sources:
        if source.is_file():
            parts.append(f"<!-- Source: {source.name} -->\n\n{source.read_text()}")
        else:
            print(f"codex-context: {source.name} missing", flush=True)
    if len(parts) == 1:
        if target.exists():
            target.unlink()  # Remove stale instructions only if owned by this generator.
        return
    # Local-only exclude: no shared .gitignore or tracked repository changes.
    exclude = Path(git("rev-parse", "--path-format=absolute", "--git-path", "info/exclude"))
    prefix = git("rev-parse", "--show-prefix")
    pattern = "/" + prefix + "AGENTS.md"
    exclude.parent.mkdir(parents=True, exist_ok=True)
    previous = exclude.read_text() if exclude.exists() else ""
    if pattern not in previous.splitlines():
        with exclude.open("a") as stream:
            stream.write(("\n" if previous and not previous.endswith("\n") else "") + pattern + "\n")
    atomic_write(target, "\n\n".join(parts) + "\n")


if __name__ == "__main__":
    try:
        bootstrap(Path.cwd(), Path(os.environ["CODEX_HOME"]), os.environ.get("JAIL_HOMELAB_SEAT") == "1")
    except RuntimeError as error:
        raise SystemExit(f"codex-context: {error}") from None
